CREATE TABLE rol (
    id BIGINT PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE privilegio (
    id BIGINT PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE rol_privilegio (
    rol_id BIGINT NOT NULL REFERENCES rol(id),
    privilegio_id BIGINT NOT NULL REFERENCES privilegio(id),
    PRIMARY KEY (rol_id, privilegio_id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    rol_id BIGINT NOT NULL REFERENCES rol(id)
);

CREATE TABLE lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    hectareas DOUBLE PRECISION NOT NULL CHECK (hectareas > 0),
    cultivo VARCHAR(100) NOT NULL,
    valle VARCHAR(80) NOT NULL,
    campania_cerrada BOOLEAN NOT NULL DEFAULT FALSE,
    dosis_maxima_por_hectarea DOUBLE PRECISION NOT NULL CHECK (dosis_maxima_por_hectarea > 0)
);

CREATE TABLE labor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('RIEGO', 'FUMIGACION', 'COSECHA')),
    fecha DATE NOT NULL,
    responsable_usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    cantidad DOUBLE PRECISION NOT NULL CHECK (cantidad >= 0),
    observacion VARCHAR(500) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE INDEX idx_lote_valle_estado ON lote(valle, campania_cerrada);
CREATE INDEX idx_labor_lote_fecha ON labor(lote_id, fecha DESC, creado_en DESC);
